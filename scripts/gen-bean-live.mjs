#!/usr/bin/env node
// Writes src/components/night/bean-mascot.gen.js from the lead studio mascot
// page (crowsnest documents/brand/mascot/index.html): the Mascot class, its
// shaders, face painter and scene helpers, unchanged except for the patches
// below. Each patch anchor must exist, so a source change fails loudly.
// Run: node scripts/gen-bean-live.mjs        (rewrite the module)
//      node scripts/gen-bean-live.mjs --check (exit 1 if it is out of date)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const OUT = join(ROOT, "src/components/night/bean-mascot.gen.js");
const CROWSNEST = process.env.CROWSNEST ?? "/Users/kienbeovl/Desktop/kaiships/crowsnest";
const REF = "origin/main:documents/brand/mascot/index.html";

const html = execFileSync("git", ["-C", CROWSNEST, "show", REF], { encoding: "utf8" });

function between(src, from, to) {
  const a = src.indexOf(from);
  const b = src.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error(`mascot source changed, cut anchor missing: ${a < 0 ? from : to}`);
  return src.slice(a + from.length, b);
}
function patch(src, from, to) {
  if (!src.includes(from)) throw new Error(`mascot source changed, patch anchor missing: ${from}`);
  return src.replace(from, to);
}

// The library half of the page script: everything before the page's own hero canvas and UI.
let js = between(html, "import * as THREE from 'https://cdnjs.cloudflare.com/ajax/libs/three.js/0.160.0/three.module.min.js';\n", "// hero\n");

// The site never loads this module under reduced motion, and tears it down if that turns on.
js = patch(
  js,
  "const mq = matchMedia('(prefers-reduced-motion: reduce)');\nlet REDUCED = mq.matches;\nmq.addEventListener('change', e => { REDUCED = e.matches; });\n",
  "const REDUCED = false;\n",
);
js = patch(js, "const Q = new URLSearchParams(location.search);\n", "");
js = patch(js, "const STILL = Q.has('still');\nif (STILL) document.documentElement.classList.add('still');\n", "const STILL = false;\n");
// The sales page is dark, and the stills were rendered with ?theme=dark.
js = patch(js, "let THEME_DARK = false;", "const THEME_DARK = true;");
// The page's one confetti moment is the DOM confetti by the final buy button.
js = patch(js, "    if (celebrate && !this.conf) this.initConfetti();\n", "");
// The registry only feeds the page's tile UI, and would keep every Bean alive.
js = patch(js, "const allMascots = new Set();\n", "");
js = patch(js, "    allMascots.add(this);\n", "");

// What src/components/night/bean-mascot.gen.d.ts promises.
for (const api of ["class Mascot {", "  setExpr(e) {", "  setPose(p) {", "  bounce() {", "  update(t, dt) {", "this.gazeTarget =", "this.happyUntil =", "this.nextBlink =", "this.seed =", "function makeScene(m) {", "function makeCam(z = 6.4, ty = 0.14) {"]) {
  if (!js.includes(api)) throw new Error(`mascot source changed, API missing: ${api}`);
}

const out = `/* eslint-disable */
// Generated by scripts/gen-bean-live.mjs from crowsnest ${REF}. Do not edit; rerun the script.
import * as THREE from "three";
${js.trimEnd()}

export { Mascot, makeScene, makeCam };
`;

if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== out) {
    console.error(`${OUT} is out of date: run node scripts/gen-bean-live.mjs`);
    process.exit(1);
  }
  console.log("bean-mascot.gen.js matches the source");
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT} (${out.length} chars)`);
}
